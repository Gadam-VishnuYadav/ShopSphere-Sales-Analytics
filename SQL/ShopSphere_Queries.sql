    SELECT
        P.CATEGORY,
        SUM(OD.SALES_AMOUNT) AS CATEGORY_REVENUE,
        (SUM(OD.PROFIT ) / SUM(OD.SALES_AMOUNT) ) * 100 AS PROFIT_MARGIN
