-- 42.IDENTIFY THE TOP 20% OF CUSTOMERS BY REVENUE
WITH CUSTOMERS_REVENUE AS (
    SELECT
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME,
        SUM(OD.SALES_AMOUNT) AS TOTAL_REVENUE
    FROM CUSTOMERS AS C
    INNER JOIN ORDERS AS O
        ON C.CUSTOMER_ID = O.CUSTOMER_ID
    INNER JOIN ORDER_DETAILS AS OD
        ON O.ORDER_ID = OD.ORDER_ID
    GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME),
    RANKED_CUSTOMER AS (
        SELECT
            CUSTOMER_ID,
            CUSTOMER_NAME,
            TOTAL_REVENUE,
            ROW_NUMBER() OVER(ORDER BY TOTAL_REVENUE DESC) AS RN,
            COUNT(*) OVER () AS TOTAL_CUSTOMER_COUNT
        FROM CUSTOMERS_REVENUE)
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    TOTAL_REVENUE
FROM RANKED_CUSTOMER
WHERE RN <= CEIL(TOTAL_CUSTOMER_COUNT * 0.20)
ORDER BY TOTAL_REVENUE DESC;

-- 43.FIND THE BEST-PERFORMING CITY FOR EACH PRODUCT CATEGORY
WITH CITY_REVENUE AS (
    SELECT
        C.CITY,
        P.CATEGORY,
        SUM(OD.SALES_AMOUNT) AS REVENUE
    FROM CUSTOMERS AS C
    INNER JOIN ORDERS AS O
        ON C.CUSTOMER_ID = O.CUSTOMER_ID
    INNER JOIN ORDER_DETAILS AS OD
        ON O.ORDER_ID = OD.ORDER_ID
    INNER JOIN PRODUCTS AS P
        ON OD.PRODUCT_ID = P.PRODUCT_ID
    GROUP BY C.CITY, P.CATEGORY),
    RANKED_CITY AS (
        SELECT
            CITY,
            CATEGORY,
            REVENUE,
            ROW_NUMBER() OVER(PARTITION BY CATEGORY ORDER BY REVENUE DESC) AS RN
        FROM CITY_REVENUE)
SELECT
    CITY,
    CATEGORY,
    REVENUE
FROM RANKED_CITY
WHERE RN = 1;

