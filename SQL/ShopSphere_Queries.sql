-- 40.IDENTIFY THE MONTH WITH THE HIGHEST REVENUE GROWTH
WITH REVENUE_GROWTH AS (
    SELECT
        MONTH(O.ORDER_DATE) AS MONTH_NUMBER,
        MONTHNAME(O.ORDER_DATE) AS MONTH_NAME,
        SUM(OD.SALES_AMOUNT) AS CURRENT_MONTH_REVENUE,
        LAG(SUM(OD.SALES_AMOUNT)) OVER(ORDER BY MONTH(O.ORDER_DATE)) AS PREVIOUS_MONTH_REVENUE
    FROM ORDERS AS O
    INNER JOIN ORDER_DETAILS AS OD
        ON O.ORDER_ID = OD.ORDER_ID
    GROUP BY MONTH(O.ORDER_DATE), MONTHNAME(O.ORDER_DATE))
SELECT
    MONTH_NAME,
    CURRENT_MONTH_REVENUE,
    PREVIOUS_MONTH_REVENUE,
    (
            (CURRENT_MONTH_REVENUE - PREVIOUS_MONTH_REVENUE ) / PREVIOUS_MONTH_REVENUE) * 100 AS REVENUE_GROWTH
FROM
    REVENUE_GROWTH
WHERE (
        (CURRENT_MONTH_REVENUE - PREVIOUS_MONTH_REVENUE ) / PREVIOUS_MONTH_REVENUE) * 100 = (
    SELECT
        MAX(
                ((CURRENT_MONTH_REVENUE - PREVIOUS_MONTH_REVENUE ) / PREVIOUS_MONTH_REVENUE) * 100
        )
    FROM REVENUE_GROWTH);

