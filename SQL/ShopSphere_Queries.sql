-- 34.CALCULATE MONTH-OVER-MONTH REVENUE GROWTH PERCENTAGE
WITH MONTHLY_REVENUE AS (
    SELECT
        MONTH(O.ORDER_DATE) AS MONTH_NUMBER,
        MONTHNAME(O.ORDER_DATE) AS MONTH_NAME,
        SUM(OD.SALES_AMOUNT) AS CURRENT_MONTH_SALES_AMOUNT
    FROM
        ORDERS AS O
    INNER JOIN ORDER_DETAILS AS OD
        ON O.ORDER_ID = OD.ORDER_ID
    GROUP BY MONTH(O.ORDER_DATE), MONTHNAME(O.ORDER_DATE))
SELECT
    MONTH_NAME,
    CURRENT_MONTH_SALES_AMOUNT,
    LAG(CURRENT_MONTH_SALES_AMOUNT) OVER(ORDER BY MONTH_NUMBER) AS PREVIOUS_MONTH_SALES_AMOUNT,
    (
            ( CURRENT_MONTH_SALES_AMOUNT - LAG(CURRENT_MONTH_SALES_AMOUNT) OVER(ORDER BY MONTH_NUMBER) ) / (LAG(CURRENT_MONTH_SALES_AMOUNT) OVER(ORDER BY MONTH_NUMBER))
    ) * 100 AS MOM_GROWTH
FROM MONTHLY_REVENUE
GROUP BY MONTH_NUMBER,MONTH_NAME;

